import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { isErrno } from "./errors.js";
import { writeFileAtomic } from "./fsutil.js";

/** Files sa generates. Ticket folders (spec.md, eval.md) are NOT ignored: they are committed. */
export const GITIGNORE_LINES: readonly string[] = [
  ".superagent/state.json",
  ".superagent/state.lock",
  ".superagent/events.jsonl",
  ".superagent/tickets/board.md",
];

const HEADER = "# Super Agent: generated by sa";

/** Add any missing sa lines to .gitignore text. Idempotent. */
export function ensureGitignore(text: string): { text: string; changed: boolean } {
  const present = new Set(text.split(/\r?\n/).map((l) => l.trim()));
  const missing = GITIGNORE_LINES.filter((l) => !present.has(l));
  if (missing.length === 0) return { text, changed: false };

  let out = text;
  if (out.length && !out.endsWith("\n")) out += "\n";
  if (!present.has(HEADER)) out += `${out.length ? "\n" : ""}${HEADER}\n`;
  out += `${missing.join("\n")}\n`;
  return { text: out, changed: true };
}

/** Update the repo's .gitignore; returns whether it changed. */
export async function updateGitignore(repoRoot: string): Promise<boolean> {
  const file = join(repoRoot, ".gitignore");
  let text = "";
  try {
    text = await readFile(file, "utf8");
  } catch (e) {
    if (!isErrno(e, "ENOENT")) throw e;
  }
  const result = ensureGitignore(text);
  if (result.changed) await writeFileAtomic(file, result.text);
  return result.changed;
}
