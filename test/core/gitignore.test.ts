import { describe, expect, it } from "vitest";
import { GITIGNORE_LINES, ensureGitignore } from "../../src/core/gitignore.js";

describe("ensureGitignore", () => {
  it("lists sa's generated files", () => {
    expect(GITIGNORE_LINES).toEqual([
      ".superagent/state.json",
      ".superagent/state.lock",
      ".superagent/events.jsonl",
      ".superagent/tickets/board.md",
      ".superagent/runs/",
    ]);
  });

  it("creates the block in an empty file", () => {
    const { text, changed } = ensureGitignore("");
    expect(changed).toBe(true);
    expect(text).toBe(`# Super Agent: generated by sa\n${GITIGNORE_LINES.join("\n")}\n`);
  });

  it("appends after existing content, adding a newline if the file lacks one", () => {
    const { text } = ensureGitignore("node_modules/");
    expect(text.startsWith("node_modules/\n\n# Super Agent: generated by sa\n")).toBe(true);
  });

  it("adds only the missing lines", () => {
    const { text, changed } = ensureGitignore("dist/\n.superagent/state.json\n");
    expect(changed).toBe(true);
    expect(text.match(/\.superagent\/state\.json/g)).toHaveLength(1);
    expect(text).toContain(".superagent/events.jsonl");
  });

  it("is idempotent", () => {
    const once = ensureGitignore("dist/\n").text;
    expect(ensureGitignore(once)).toEqual({ text: once, changed: false });
  });
});
