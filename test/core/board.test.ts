import { describe, expect, it } from "vitest";
import { renderBoard } from "../../src/core/board.js";
import { state, ticket, ticketIn } from "../helpers.js";

describe("renderBoard", () => {
  it("renders the board table sorted by id", () => {
    const s = state({
      "002": ticket({ title: "Filter by tag", dependsOn: ["001", "003"] }),
      "001": ticketIn("review", { title: "Add tags | labels", pr: "https://github.com/o/r/pull/4" }),
      "003": ticketIn("in_progress", { title: "Search notes", mode: "team" }),
    });

    expect(renderBoard(s)).toBe(
      [
        "# Board",
        "",
        "<!-- Generated by sa from .superagent/state.json. Do not edit by hand. -->",
        "",
        "Run 2026-11-16-a · max 2 workers · budget 2,000,000 tokens",
        "",
        "| ID | Title | Status | Mode | Runs | PR |",
        "| --- | --- | --- | --- | --- | --- |",
        "| 001 | Add tags \\| labels | review | solo | alone | https://github.com/o/r/pull/4 |",
        "| 002 | Filter by tag | draft | solo | after 001, 003 | – |",
        "| 003 | Search notes | in_progress | team | alone | – |",
        "",
      ].join("\n"),
    );
  });

  it("renders an empty board", () => {
    expect(renderBoard(state())).toContain("_No tickets yet._");
  });
});
